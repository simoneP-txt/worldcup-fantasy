export const LANG_NAMES = { en: "English", it: "Italiano" };

let current = "en";

export function setLang(lang) {
  if (I18N[lang]) current = lang;
  document.documentElement.lang = current;
}

export function getLang() {
  return current;
}

export function t(key, params) {
  const table = I18N[current] || I18N.en;
  let s = table[key];
  if (s === undefined) s = I18N.en[key];
  if (s === undefined) return key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

// Display label for a backend role string (CAPTAIN/VICE/START/bench GK/sub N/bench).
export function roleLabel(role) {
  if (role === "CAPTAIN") return t("role.CAPTAIN");
  if (role === "VICE") return t("role.VICE");
  if (role === "START") return t("role.START");
  if (role === "bench GK") return t("role.benchGK");
  if (role && role.startsWith("sub ")) return `${t("role.sub")} ${role.slice(4)}`;
  return t("role.bench");
}
